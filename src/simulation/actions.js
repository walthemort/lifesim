import * as racing from './racing.js';
import * as sport from './sports.js';
import * as firms from './businesses.js';
import * as school from "./education.js";
import * as health from "./health.js";
import * as social from "./social.js";
import * as mobility from "./mobility.js";
import * as home from "./home.js";
import * as work from "./professions.js";
export function simulationCommand(s, operation, p = {}) {
  const actions = {
    'racing-detail':()=>racing.openRaceEngineering(s),
    'kart-budget':()=>racing.fundKartSeason(s),
    'kart-equipment':()=>racing.chooseKartEquipment(s,p.chassis,p.engine),
    'race-weekend':()=>racing.startRaceWeekend(s,p.fixture),
    'race-practice':()=>racing.practiceRace(s),
    'race-feedback':()=>racing.raceFeedback(s),
    'race-setup':()=>racing.configureRace(s,{balance:Number(p.balance),downforce:Number(p.downforce),strategy:p.strategy,tyre:p.tyre,teamOrder:p.teamOrder}),
    'race-qualifying':()=>racing.qualifyRace(s),
    'race-service':()=>racing.serviceRaceComponent(s,p.component),
    'race-discipline':()=>racing.changeRacingDiscipline(s,p.discipline),
    'race-reserve':()=>racing.beginReserveDuties(s),
    'reserve-duty':()=>racing.deliverReserveDuties(s,p.kind),
    'sport-detail':()=>sport.openDetailedSport(s,p.sport),
    'combination':()=>sport.footballCombination(s,p.teammate),
    'card-appeal':()=>sport.appealFootballCard(s),
    'basketball-assignment':()=>sport.requestDevelopmentAssignment(s),
    'tennis-entry':()=>sport.enterTennisTournament(s,p.fixture,p.draw),
    'boxing-join':()=>sport.joinBoxingGym(s),
    'boxing-leave':()=>sport.leaveBoxing(s),
    'boxing-train':()=>sport.trainBoxing(s,p.focus),
    'boxing-medical':()=>sport.boxingMedical(s),
    'boxing-bout':()=>sport.requestBoxingBout(s),
    'boxing-licence':()=>sport.applyBoxingLicence(s),
    'business-open':()=>firms.openBusinessOperations(s,p.firm),
    'employee-hire':()=>firms.hireEmployee(s,p.firm,p.role),
    'employee-manage':()=>firms.manageEmployee(s,p.firm,p.employee,p.method),
    'supplies':()=>firms.orderSupplies(s,p.firm,p.supplier,Number(p.units)),
    'segment':()=>firms.setCustomerSegment(s,p.firm,p.segment,Number(p.price)),
    'equity-seek':()=>firms.seekEquity(s,p.firm),
    'equity-accept':()=>firms.acceptEquity(s,p.firm),
    'diligence':()=>firms.conductDueDiligence(s,p.target),
    'board':()=>firms.proposeBoardDecision(s,p.firm,p.proposal),
    'branch':()=>firms.openBranch(s,p.firm,p.city,p.kind),
    'stadium':()=>firms.buildMatchdayStand(s,p.firm),
    'tickets':()=>firms.setTicketPrice(s,p.firm,Number(p.price)),
    'venue-approach':()=>firms.approachOwnershipFormat(s,p.kind),
    'venue-buy':()=>firms.buyOwnershipFormat(s,p.kind),
    'venue-fund':()=>firms.fundOwnershipFormat(s,p.venue,Number(p.amount)),
    "professional-open": () => work.openProfessionalDesk(s),
    "professional-case": () => work.newProfessionalCase(s),
    "professional-practice": () => work.professionalPractice(s, p.method),
    "specialise": () => work.beginSpecialisation(s, p.field),
    "specialist-assessment": () => work.assessSpecialisation(s),
    "client-trade": () => work.tradeForClient(s, p.client, p.asset, Number(p.amount)),
    "internal-vacancy": () => work.reviewInternalVacancy(s),
    "fleet-start": () => mobility.startFleetManagement(s),
    "licence-lesson": () => mobility.licenceLesson(s, p.licence),
    "licence-exam": () => mobility.sitLicenceExam(s, p.licence),
    "commute": () => mobility.changeCommute(s, p.mode, p.vehicle),
    "vehicle-service": () => mobility.serviceVehicle(s, p.vehicle),
    "vehicle-insure": () => mobility.insureVehicle(s, p.vehicle, p.cover),
    "vehicle-uninsure": () => mobility.cancelVehicleInsurance(s, p.vehicle),
    "vehicle-trip": () => mobility.vehicleTrip(s, p.vehicle, p.route, p.operator),
    "vehicle-repair": () => mobility.repairVehicle(s, p.vehicle),
    "vehicle-claim": () => mobility.claimInsurance(s, p.vehicle),
    "vehicle-finance": () => mobility.financeVehicle(s, p.vehicle, p.kind),
    "vehicle-settle": () => mobility.repayVehicleFinance(s, p.contract),
    "vehicle-storage": () => mobility.rentVehicleStorage(s, p.type, Number(p.spaces)),
    "vehicle-inspect": () => mobility.inspectUsedVehicle(s, p.offer),
    "vehicle-used": () => mobility.buyUsedVehicle(s, p.offer, Number(p.fraction)),
    "outfit-context": () => home.setDressContext(s, p.context),
    "furniture": () => home.placeFurniture(s, p.item, p.room, p.property),
    "renovate": () => home.startRenovation(s, p.property, p.type, p.contractor),
    "renovation-cancel": () => home.cancelRenovation(s, p.project),
    "explore": () => school.exploreAptitude(s, p.subject),
    "study": () => school.studySubject(s, p.subject),
    "teacher": () => school.talkTeacher(s, p.subject),
    "school": () => school.applySchool(s, p.school),
    "assess": () => school.assessLearning(s),
    "support-plan": () => school.setLearningPlan(s, p.plan),
    "bullying": () => school.reportBullying(s, p.response),
    "exams": () => school.sitSubjectExams(s),
    "parent": () => school.discussParenting(s, p.person, p.topic),
    "health-start": () => health.startHealthRecord(s),
    "appointment": () => health.bookAppointment(s, p),
    "treatment": () => health.chooseTreatment(s, p.condition, p.treatment),
    "nutrition": () => health.setNutrition(s, p.plan),
    "habit": () => health.practiceHabit(s, p.habit),
    "rehab": () => health.injuryRehab(s, p.injury),
    "network": () => social.discoverSocialLinks(s, p.person),
    "introduction": () => social.requestFriendIntroduction(s, p.person),
    "affection": () => social.showAffection(s, p.person, p.kind),
    "promise": () => social.makeSocialPromise(s, p.person, p.kind),
    "grievance": () => social.addressGrievance(s, p.grievance),
    "plan": () => social.discussLifePlan(s, p.topic, p.choice),
    "family-intro": () => social.introduceExtendedFamily(s),
    "family-visit": () => social.visitExtendedFamily(s, p.person),
    "counselling-start": () => social.startCounselling(s),
    "counselling": () => social.attendCounselling(s),
    "ambition": () => social.supportChildAmbition(s, p.child, p.support === "yes"),
    "prenup": () => social.signPrenup(s, p.policy),
    "adult-support": () => social.supportAdultChild(s, p.child, Number(p.amount)),
  };
  if (!Object.hasOwn(actions, operation)) throw new Error("This detailed activity is unavailable.");
  return actions[operation]();
}
